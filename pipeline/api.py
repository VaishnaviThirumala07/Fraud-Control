# ── Managed Stream Control (On-Demand & Idle Auto-Pause) ──────────────────────

is_producer_running = False
producer_task = None

@app.get("/api/stream/status")
async def get_stream_status():
    """Return streaming status and active UI client count."""
    return {
        "is_streaming": is_producer_running,
        "active_ui_clients": len(manager.active_connections)
    }

@app.post("/api/stream/start")
async def start_stream(interval_seconds: int = 20):
    """Start streaming transactions on-demand."""
    global is_producer_running, producer_task
    if is_producer_running:
        return {"status": "already_running"}
    is_producer_running = True
    producer_task = asyncio.create_task(run_managed_stream(interval_seconds))
    return {"status": "started", "interval_seconds": interval_seconds}

@app.post("/api/stream/stop")
async def stop_stream():
    """Stop/pause streaming transactions immediately to save credits."""
    global is_producer_running
    is_producer_running = False
    return {"status": "stopped"}

async def run_managed_stream(interval_seconds: int = 20):
    """Managed background transaction stream loop with auto-pause guardrails."""
    global is_producer_running
    print(f"[Managed Stream] Producer loop started (Interval: {interval_seconds}s).")
    idle_count = 0
    try:
        data_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
        tx_path = os.path.join(data_dir, "aligned_transactions.csv")
        prof_path = os.path.join(data_dir, "customer_profiles.csv")
        
        if not os.path.exists(tx_path) or not os.path.exists(prof_path):
            print("[Managed Stream] Data files missing.")
            is_producer_running = False
            return

        tx_df = pd.read_csv(tx_path)
        profiles_df = pd.read_csv(prof_path).set_index("customer_id")

        for _, tx_row in tx_df.iterrows():
            if not is_producer_running:
                break
            
            # Idle Auto-Stop Timeout: auto-pause if no UI clients connected for 2+ minutes
            if len(manager.active_connections) == 0:
                idle_count += interval_seconds
                if idle_count >= 120:
                    print("[Managed Stream] Auto-pausing stream: No active UI connected for 2 minutes.")
                    is_producer_running = False
                    break
            else:
                idle_count = 0

            cust_id = tx_row['customer_id']
            if cust_id not in profiles_df.index:
                continue

            tx_dict = {k: (None if pd.isna(v) else v) for k, v in tx_row.to_dict().items()}
            prof_dict = {k: (None if pd.isna(v) else v) for k, v in profiles_df.loc[cust_id].to_dict().items()}
            prof_dict["customer_id"] = cust_id

            msg_payload = json.dumps({"transaction": tx_dict, "profile": prof_dict}).encode('utf-8')
            await process_message(msg_payload)
            await asyncio.sleep(interval_seconds)
    except Exception as e:
        print(f"[Managed Stream] Exception in stream loop: {e}")
    finally:
        is_producer_running = False
        print("[Managed Stream] Producer loop stopped.")


