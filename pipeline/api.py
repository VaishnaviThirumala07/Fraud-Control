# ── Neo4j Graph Ingestion ─────────────────────────────────────────────────────

async def ingest_to_graph(tx: dict, prof: dict):
    try:
        driver = AsyncGraphDatabase.driver(NEO4J_URI, auth=(NEO4J_USER, NEO4J_PASSWORD))
        async with driver.session() as session:
            query = """
            MERGE (u:User {id: $customer_id})
            MERGE (t:TransactionNode {id: $tx_id})
            SET t.amount = $amount, t.type = $type
            MERGE (u)-[:PERFORMED]->(t)
            """
            import uuid
            await session.run(query,
                customer_id=tx['customer_id'],
                tx_id=str(tx.get('step', '0')) + "_" + tx['customer_id'] + "_" + uuid.uuid4().hex[:8],
                amount=float(tx['amount']),
                type=tx['type']
            )
        await driver.close()
        print(f"Ingested TX {tx['customer_id']} to Neo4j")
    except Exception as e:
        print(f"Graph ingestion failed: {e}")


# ── Core Message Processor ────────────────────────────────────────────────────

async def process_message(msg_value):
    try:
        data = json.loads(msg_value.decode('utf-8'))
        tx = data["transaction"]
        prof = data["profile"]

        # 0. Continuous graph ingestion (fire-and-forget)
        asyncio.create_task(ingest_to_graph(tx, prof))

        # 1. Fast Path: XGBoost + TabNet
        result = predict_risk(tx)
        transaction_id = str(
            tx.get("transaction_id")
            or f"{tx.get('step', '0')}:{tx['customer_id']}:{tx.get('nameDest', '')}"
        )
        action_engine.register_transaction(
            transaction_id=transaction_id,
            customer_id=tx["customer_id"],
            is_flagged=result["is_flagged"],
        )

        fast_path_payload = {
            "type": "FAST_PATH",
            "transaction_id": transaction_id,
            "transaction": tx,
            "profile": prof,
            "fast_path_result": result,
            "stats": action_engine.get_action_stats(),
            "blocked_accounts": action_engine.blocked_accounts[-10:],
            "alerts": action_engine.alert_feed[-8:],
        }
        dashboard_transactions[transaction_id] = {
            "id": transaction_id,
            "transaction": tx,
            "profile": prof,
            "fastPathResult": result,
            "report": None,
            "actionResult": None,
            "manual": False,
        }
        await manager.broadcast(fast_path_payload)

        # 2. Slow Path (only if flagged)
        if result["is_flagged"]:
            tx_data = TransactionData(
                customer_id=tx["customer_id"],
                type=tx["type"],
                amount=tx["amount"],
                oldbalanceOrg=tx["oldbalanceOrg"],
                oldbalanceDest=tx["oldbalanceDest"],
                risk_score=result["risk_score"],
                ml_flagged=result["is_flagged"],
            )
            cust_data = CustomerData(
                customer_id=prof["customer_id"],
                kyc_status=prof["kyc_status"],
                pep_status=bool(prof["pep_status"]),
                risk_tier=prof["risk_tier"],
                account_age_days=int(prof["account_age_days"]),
                unique_counterparties_30d=int(prof["unique_counterparties_30d"]),
                shared_ip_count=int(prof["shared_ip_count"]),
                recent_failed_logins=int(prof["recent_failed_logins"]),
                session_velocity_seconds=int(prof["session_velocity_seconds"]),
                historical_avg_tx_amount=float(prof["historical_avg_tx_amount"]),
            )

            async with slow_path_semaphore:
                report = await investigate(tx_data, cust_data)

            # 3. Action Agent: autonomously execute the decision
            action_result = await action_engine.execute_action(
                customer_id=tx["customer_id"],
                recommended_action=report.recommended_action,
                risk_score=report.risk_score,
                reasons=report.reasons,
                sar_explanation=report.sar_explanation,
                transaction_amount=float(tx["amount"]),
                transaction_type=tx["type"],
                transaction_id=transaction_id,
            )

            # 4. Memory Agent: persist this investigation for future reference
            memory_engine.store_investigation(
                customer_id=tx["customer_id"],
                risk_score=report.risk_score,
                action=report.recommended_action,
                flags=report.reasons,
                explanation=report.sar_explanation,
                tx_amount=float(tx["amount"]),
                tx_type=tx["type"],
            )

            # 5. Broadcast SLOW_PATH result
            slow_path_payload = {
                "type": "SLOW_PATH",
                "transaction_id": transaction_id,
                "customer_id": tx["customer_id"],
                "report": report.model_dump(),
            }
            dashboard_transactions[transaction_id]["report"] = report.model_dump()
            await manager.broadcast(slow_path_payload)

            # 6. Broadcast ACTION_TAKEN event
            dashboard_transactions[transaction_id]["actionResult"] = action_result
            await manager.broadcast({
                "type": "ACTION_TAKEN",
                "transaction_id": transaction_id,
                "customer_id": tx["customer_id"],
                "action_result": action_result,
                "stats": action_engine.get_action_stats(),
                "blocked_accounts": action_engine.blocked_accounts[-10:],
                "alerts": action_engine.alert_feed[-8:],
            })

    except Exception as e:
        print(f"Error processing message: {e}")
        import traceback; traceback.print_exc()


# ── Message Queue Consumers ───────────────────────────────────────────────────

async def rabbitmq_consumer_task():
    import aio_pika
    print(f"Connecting to RabbitMQ/CloudAMQP at {CLOUDAMQP_URL}...")

    connection = None
    for _ in range(5):
        try:
            connection = await aio_pika.connect_robust(CLOUDAMQP_URL)
            break
        except Exception as e:
            print(f"Waiting for RabbitMQ... {e}")
            await asyncio.sleep(2)

    if not connection:
        print("Failed to connect to RabbitMQ.")
        return

    print("RabbitMQ/CloudAMQP Consumer started successfully!")
    async with connection:
        channel = await connection.channel()
        queue = await channel.declare_queue(TOPIC, durable=True)

        async with queue.iterator() as queue_iter:
            async for message in queue_iter:
                async with message.process():
                    asyncio.create_task(process_message(message.body))


async def kafka_consumer_task():
    consumer = AIOKafkaConsumer(
        TOPIC,
        bootstrap_servers=KAFKA_BROKER,
        group_id="fraud-consumer-group",
        auto_offset_reset="latest"
    )
    for _ in range(5):
        try:
            await consumer.start()
            break
        except Exception:
            await asyncio.sleep(2)

    print("Kafka Consumer started successfully!")
    try:
        async for msg in consumer:
            asyncio.create_task(process_message(msg.value))
    finally:
        await consumer.stop()


@app.on_event("startup")
async def startup_event():
    # Build or load the RAG policy index before accepting transaction work.
    # This avoids paying the indexing cost during the first flagged message.
    await initialize_policy_index()

    if CLOUDAMQP_URL:
        asyncio.create_task(rabbitmq_consumer_task())
    else:
        asyncio.create_task(kafka_consumer_task())


